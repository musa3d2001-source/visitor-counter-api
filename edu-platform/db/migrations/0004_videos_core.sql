-- =====================================================================
-- 0004: الفيديو أصبح ميزة أساسية في المنصة
-- قاعدة بيانات حفظ فيها المالك الإعدادات سابقًا قد تحتفظ بـ videos_enabled=false
-- (القيمة الافتراضية القديمة)، فتختفي كل المشغلات. نفعّلها مرة واحدة،
-- ويبقى بإمكان المالك إيقافها لاحقًا من «إعدادات المنصة».
-- =====================================================================
update settings set value = 'true'::jsonb, updated_at = now() where key = 'videos_enabled';
