// [تجربة المرحلة 0 - كود مؤقت] يولّد جدول التصويب الصحيح (cos/sin × 1e6) مرة واحدة خارج المحرك.
// المحرك نفسه لا يستدعي Math.cos/sin (القائمة البيضاء)، بل يقرأ هذه الأعداد الصحيحة الثابتة.
// التشغيل: node scripts/game-spike/gen-aim-table.mjs > src/app/admin/game/spike/_engine/aim-table.generated.ts
const ANGLE_MIN_DEG = 0;
const ANGLE_STEPS = 81; // 0..80 درجة بخطوة درجة واحدة
const cos = [];
const sin = [];
for (let i = 0; i < ANGLE_STEPS; i++) {
  const rad = ((ANGLE_MIN_DEG + i) * Math.PI) / 180;
  cos.push(Math.round(Math.cos(rad) * 1e6));
  sin.push(Math.round(Math.sin(rad) * 1e6));
}
const out = `// GENERATED by scripts/game-spike/gen-aim-table.mjs - do not edit by hand.
// [Phase 0 spike] integer cos/sin of angleStep degrees, scaled by 1e6.
export const ANGLE_MIN_DEG = ${ANGLE_MIN_DEG};
export const ANGLE_STEPS = ${ANGLE_STEPS};
export const COS_1E6: readonly number[] = [${cos.join(", ")}];
export const SIN_1E6: readonly number[] = [${sin.join(", ")}];
`;
process.stdout.write(out);
