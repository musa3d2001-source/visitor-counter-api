/** أرباح البيع تبقى معلقة هذه المدة من تأكيد الدفع، وهي نفسها مهلة طلب الاسترداد في سياسة الاسترداد */
export const REFUND_HOLD_DAYS = 7;

/**
 * آيبان في نص حر: حرفان ثم رقمان ثم ما يكمل طول آيبانات الخليج (٢٢ إلى ٣٠ خانة)، أو كلمة «آيبان» نفسها.
 * أرقام التحويل المعتادة أقصر من ذلك فلا تتأثر. الهدف منع حفظ حساب المعلم البنكي في السجل، وهو فحص أفضل جهد.
 */
export function looksLikeBankDetails(text: string): boolean {
  const compact = text.replace(/[٠-٩]/g, (d) => String("٠١٢٣٤٥٦٧٨٩".indexOf(d))).replace(/[\s-]/g, "");
  return /[a-z]{2}\d{2}[a-z0-9]{18,30}/i.test(compact) || /iban|[اآ]يبان/i.test(compact);
}
