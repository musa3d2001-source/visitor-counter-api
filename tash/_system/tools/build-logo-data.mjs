// Generates _system/brand/logo-data.mjs from the licensed OFL fonts (outlined, no font needed at runtime).
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const SYS = join(dirname(fileURLToPath(import.meta.url)), '..');
const g = (font, axes, text) => JSON.parse(execFileSync('python3', [join(SYS, 'tools/glyphs.py'), join(SYS, 'fonts', font), axes, text]).toString());

// 1) Arabic body: dotless "طس" in Alexandria Black, with the ط stem re-cut at an angle (rises toward the reading direction).
const body = g('Alexandria-VF.ttf', '900', 'طس');
const STEM_ORIG = 'M1840 -141V-901H2033V-275Z';
const STEM_CUT = 'M1840 -141V-960L2033 -860V-275Z';
let BODY = body.glyphs.map(x => x.d).join(' ');
if (!BODY.includes(STEM_ORIG)) throw new Error('stem contour not found — font version changed?');
BODY = BODY.replace(STEM_ORIG, STEM_CUT);
// 2) Shadda from the same font (cluster mark)
const full = g('Alexandria-VF.ttf', '900', 'طشّ');
const SHADDA = full.glyphs.find(x => x.name === 'uni0651').d;
// 3) Latin + mono outlines for lockups
const tash = g('Archivo-VF.ttf', 'wght=900,wdth=125', 'TASH');
const sub = g('JetBrainsMono-VF.ttf', '600', 'CREATIVE STUDIO · KUWAIT');
const subTracked = (track) => sub.glyphs.map((x, i) => `<path transform="translate(${i * track} 0)" d="${x.d}"/>`).join('');

const data = {
  // font units; origin = baseline. Normalised by translate(TX,TY) into viewBox 0 0 W H
  TX: -40, TY: 1227, W: 2579, H: 1461,
  BODY, SHADDA, SHADDA_DX: -15, SHADDA_DY: 60,
  DOTS: { cx: 1120, cy: -790, r: 90, gap: 32 },
  LATIN: { d: tash.glyphs.map(x => x.d).join(' '), adv: tash.advance, capH: 700, x0: 23, w: 3485 }, // measured ink bbox
  SUB: { svg: subTracked(240), adv: sub.advance + 240 * (sub.glyphs.length - 1) },
};
writeFileSync(join(SYS, 'brand/logo-data.mjs'), '// AUTO-GENERATED by tools/build-logo-data.mjs — do not edit by hand\nexport default ' + JSON.stringify(data) + ';\n');
console.log('logo-data written', Object.keys(data));
