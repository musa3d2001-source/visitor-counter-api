"""HABBA (حبّة) logo builder — outlines «حبّة» from Alexandria (OFL) at a chosen weight with HarfBuzz shaping,
removes the single dot under ب and records its position: in the mark that dot is replaced by a coffee bean
(«حبّة» = "a bean"). Writes src/habba-logo.mjs (path data + bean anchor) and review SVGs."""
import sys, json, io
import uharfbuzz as hb
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools.pens.recordingPen import DecomposingRecordingPen as _DRP
class RecordingPen(_DRP):
    def __init__(self): super().__init__(gs)
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.transformPen import TransformPen

FONT = '/home/user/visitor-counter-api/tash/_system/fonts/Alexandria-VF.ttf'
OUT = sys.argv[1]
WGHT = float(sys.argv[2]) if len(sys.argv) > 2 else 500
TEXT = 'حبّة'

vf = TTFont(FONT)
inst = instantiateVariableFont(vf, {'wght': WGHT}, inplace=False)
bio = io.BytesIO(); inst.save(bio); data = bio.getvalue()
face = hb.Face(hb.Blob(data)); font = hb.Font(face)
buf = hb.Buffer(); buf.add_str(TEXT); buf.guess_segment_properties(); hb.shape(font, buf, {})
gs = inst.getGlyphSet(); order = inst.getGlyphOrder(); upm = inst['head'].unitsPerEm

def contours_of(name, dx, dy):
    rp = RecordingPen(); gs[name].draw(TransformPen(rp, (1, 0, 0, -1, dx, -dy)))  # flip y → SVG down
    cs, cur = [], []
    for op, args in rp.value:
        cur.append((op, args))
        if op in ('closePath', 'endPath'): cs.append(cur); cur = []
    return cs

def path_of(contours):
    sp = SVGPathPen(None)
    for c in contours:
        for op, args in c: getattr(sp, op)(*args)
    return sp.getCommands()

def bbox(c):
    xs, ys = [], []
    for op, args in c:
        for p in args: xs.append(p[0]); ys.append(p[1])
    return min(xs), min(ys), max(xs), max(ys)

x = 0; body, dot = [], None
infos = list(zip(buf.glyph_infos, buf.glyph_positions))
# HarfBuzz returns visual order (left→right) for RTL runs
for info, pos in infos:
    name = order[info.codepoint]
    gx, gy = x + pos.x_offset, pos.y_offset
    cs = contours_of(name, gx, gy)
    if name == 'uniFE92':  # medial beh: split off its single dot (the lowest small contour)
        bbs = [bbox(c) for c in cs]
        idx = max(range(len(cs)), key=lambda i: bbs[i][1])  # largest y (lowest on screen)
        dot = bbs[idx]; cs = [c for i, c in enumerate(cs) if i != idx]
    body += cs
    x += pos.x_advance
allb = [bbox(c) for c in body]
x0 = min(b[0] for b in allb); y0 = min(b[1] for b in allb); x1 = max(b[2] for b in allb); y1 = max(b[3] for b in allb)
y1 = max(y1, dot[3])
d = path_of(body)
res = {'wght': WGHT, 'upm': upm, 'box': [x0, y0, x1, y1], 'body': d,
       'dot': {'cx': (dot[0] + dot[2]) / 2, 'cy': (dot[1] + dot[3]) / 2, 'r': (dot[2] - dot[0]) / 2}}
open(OUT, 'w').write('// generated by tools/build_logo.py — «حبّة» outlined from Alexandria (OFL) wght %d; the ب dot is replaced by a bean in the mark.\nexport default %s;\n' % (WGHT, json.dumps(res)))
print(json.dumps({k: v for k, v in res.items() if k != 'body'}))
